/**
 * Title vocabulary: what a headline MEANS, not which object the user names.
 *
 * `SYNONYMS` — words that point straight at one motif («деньги» → монета).
 * `THEMES`   — broader topics; each key nudges several motifs by an affinity (0..1).
 * Keys are comma separated lemmas or phrases; `:n` overrides the default weight.
 * Inflection is handled by stemming (see stem.ts), so lists hold dictionary forms plus
 * irregular forms the Snowball stemmer cannot fold («денег», «кошелька»).
 * Only motifs that exist in the Figma library appear here — nothing is invented.
 */
import type { MotifId } from '../domain/types';

export interface LexiconKey {
  text: string;
  weight?: number;
}

/** Default weight of a direct synonym / of a theme key. */
export const SYNONYM_WEIGHT = 7;
export const THEME_KEY_WEIGHT = 3;

export function parseKeys(list: string): LexiconKey[] {
  return list
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean)
    .map((part) => {
      const m = /^(.*?)\s*:\s*(\d+(?:\.\d+)?)$/.exec(part);
      return m && m[1] !== undefined && m[2] !== undefined
        ? { text: m[1], weight: Number(m[2]) }
        : { text: part };
    });
}

